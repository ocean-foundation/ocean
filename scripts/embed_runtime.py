#!/usr/bin/env python3
"""Embed the C runtime sources into compiler/runtime/source.oc as raw strings."""
import os
here = os.path.join(os.path.dirname(__file__), '..', 'compiler', 'runtime')
out = ['package runtime;', '', '// Generated by scripts/embed_runtime.py from the .c files in this directory.', '']
for name, fn in [('core.c', 'Core'), ('threads.c', 'Threads'), ('process.c', 'Process'), ('ffi.c', 'Ffi')]:
    text = open(os.path.join(here, name)).read()
    assert '`' not in text, name
    out.append('func %s() string {\n    return `%s`;\n}\n' % (fn, text))
open(os.path.join(here, 'source.oc'), 'w').write('\n'.join(out))
